function crrg_drill_travel(&$s, &$pc, $ctx, $dest, $pay) {
    $scene = crrg_drill_cur_scene();
    if ($dest === 'town') {
        if ($scene === 'town') return [false, ['你已经在镇上了。']];
        if ($scene !== 'base')  return [false, ['先从副本撤回基地。']];
        if (($s['room'] ?? '') !== 'garage_maint') return [false, ['要出山得先去车库·维修保养区。']];
    } else {
        if ($scene === 'base') return [false, ['你已经在基地里。']];
        if ($scene !== 'town')  return [false, ['这里不通基地。']];
        if (($s['room'] ?? '') !== 'tw_station') return [false, ['回基地的车在汽车站。']];
    }
    if (crrg_drill_has_vehicle($pc)) {
        $mode = '自驾' . $pc['vehicle']; $cost = 0; $field = '';
    } elseif ($pay === 'money') {
        $mode = '搭车'; $cost = 100; $field = 'money';
    } else {
        $mode = '坐基地车'; $cost = 10; $field = 'credits';
    }
    if ($field && (int) ($pc[$field] ?? 0) < $cost) {
        return [false, [sprintf('不够：%s 需要 %d %s（你现有 %d）。也可选另一种方式。',
            $mode, $cost, $field === 'credits' ? '积分' : '元', (int) ($pc[$field] ?? 0))]];
    }
    if ($field) $pc[$field] -= $cost;
    if ($dest === 'town') {
        $pc['base_room'] = $s['room'];
        $pc['scene'] = 'town';
        crrg_drill_set_scene('town');
        $s['room'] = 'tw_gate';
        $out = ['〔' . $mode . '〕沿土路上公路，二十多分钟后在镇口停下。'];
    } else {
        $pc['scene'] = 'base';
        crrg_drill_set_scene('base');
        $s['room'] = 'garage_maint';
        $out = ['〔' . $mode . '〕回到山体车库。'];
    }
    return [true, array_merge($out, crrg_drill_room_lines($s, $ctx))];
}

