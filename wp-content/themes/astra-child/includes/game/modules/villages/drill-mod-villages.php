/** 村子的落地表（车旅到村口） */
function crrg_game_travel_landing_villages() {
    $out = [];
    foreach (array_keys((array) crrg_village_specs()) as $nid) $out[$nid] = ['room' => $nid . '_gate', 'scene' => 'village_' . $nid];
    return $out;
}

/** 村房间进全局表 ＋ 出口双向对称化 */
add_action('init', function () {
    if (!function_exists('crrg_game_register_many')) return;
    $R = &crrg_drill_reg();
    foreach (array_keys((array) $R['scenes']) as $sid) {
        if (strpos((string) $sid, 'village_') !== 0) continue;
        $rooms = (array) ($R['scenes'][$sid]['rooms'] ?? []);
        if ($rooms) crrg_game_register_many('room', $rooms, ['module' => 'villages', 'file' => __FILE__]);
        if (function_exists('crrg_city_symmetrize')) crrg_city_symmetrize($sid);
    }
}, 48);
