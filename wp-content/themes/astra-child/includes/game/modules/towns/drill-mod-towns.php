/** 镇上的房间也进全局房间表 ✓ */
add_action('init', function () {
    if (!function_exists('crrg_game_register_many')) return;
    $R = &crrg_drill_reg();
    foreach (['town_heisongyi', 'town_liuhe', 'town_sandaogou', 'town_hewan'] as $sid) {
        $rooms = (array) ($R['scenes'][$sid]['rooms'] ?? []);
        if ($rooms) crrg_game_register_many('room', $rooms, ['module' => 'towns', 'file' => __FILE__]);
    }
}, 46);

