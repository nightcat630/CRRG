/** 解析节点名（可选按房间优先，避免跨房间抢名） */
function crrg_seal_path_node($arg, $room = '') {
    if ($arg === '') return '';
    $hit = '';
    foreach (crrg_seal_paths_full() as $k => $paths) {
        if (mb_strpos($k, $arg) === false && mb_strpos($arg, $k) === false) continue;
        if ($room !== '' && crrg_seal_node_room($k) === $room) return $k;
        if ($hit === '') $hit = $k;
    }
    return $hit;
}

/** 某节点是否已完成？返回已置位的旗标（否则空串） */
function crrg_seal_path_done(&$s, $node) {
    foreach ((crrg_seal_paths_full()[$node] ?? []) as $p) {
        if (in_array($p['flag'], (array) ($s['flags'] ?? []), true)) return $p['flag'];
    }
    return '';
}

/** 按线索旗标去重（同一旗标的多个节点＝同一条线索） */
function crrg_seal_nodes_dedup($nodes) {
    $seen = []; $out = [];
    foreach ((array) $nodes as $node) {
        $fl = '';
        foreach ((array) (crrg_seal_paths_full()[$node] ?? []) as $p) { $fl = (string) ($p['flag'] ?? ''); break; }
        if ($fl !== '' && isset($seen[$fl])) continue;
        if ($fl !== '') $seen[$fl] = 1;
        $out[] = $node;
    }
    return $out;
}

/** 同一条线索的兄弟节点（共用旗标） */
function crrg_seal_siblings($node) {
    $fl = '';
    foreach ((array) (crrg_seal_paths_full()[$node] ?? []) as $p) { $fl = (string) ($p['flag'] ?? ''); break; }
    if ($fl === '') return [];
    $out = [];
    foreach (crrg_seal_paths_full() as $n => $ps) foreach ($ps as $p) if ($p['flag'] === $fl && $n !== $node) { $out[] = $n; break; }
    return array_values(array_unique($out));
}

/** 「这条已经查过了」的升级版：点名、本间还剩什么、别处还有什么（含路线） */
function crrg_seal_done_msg(&$s, &$pc, $room, $kwFlag = '', $kw = '') {
    $nodeHere = '';
    foreach (crrg_seal_paths_full() as $node => $paths) {
        if (crrg_seal_node_room($node) !== $room) continue;
        foreach ($paths as $p) if ($kwFlag !== '' && $p['flag'] === $kwFlag) { $nodeHere = $node; break 2; }
        if ($nodeHere === '' && $kw !== '' && (mb_strpos($node, $kw) !== false || mb_strpos($kw, $node) !== false)) $nodeHere = $node;
    }
    /* 只提示"当前在手任务范围内"的节点 */
    $scope = [];
    foreach ([$pc['mission'] ?? '', $pc['mission2']['id'] ?? ''] as $mid) {
        $mm = function_exists('crrg_drill_mission_any') ? crrg_drill_mission_any($mid) : null;
        foreach ((array) ($mm['steps'] ?? []) as $stp) if (!empty($stp['flag'])) $scope[$stp['flag']] = 1;
    }
    $inScope = function ($node) use ($scope) {
        if (!$scope) return true;
        foreach ((array) (crrg_seal_paths_full()[$node] ?? []) as $p) if (isset($scope[$p['flag']])) return true;
        return false;
    };
    if ($nodeHere === '') {
        $hereScoped = [];
        foreach (crrg_seal_paths_full() as $n0 => $p0) if (crrg_seal_node_room($n0) === $room && $inScope($n0)) $hereScoped[] = $n0;
        if (count($hereScoped) === 1) $nodeHere = $hereScoped[0];
        elseif ($hereScoped) { foreach ($hereScoped as $n1) if (crrg_seal_path_done($s, $n1)) { $nodeHere = $n1; break; } }
    }
    $sib = $nodeHere !== '' ? crrg_seal_siblings($nodeHere) : [];
    $out = [$nodeHere !== ''
        ? sprintf('（「%s」你已经查过了%s。）', $nodeHere, $sib ? '——和「' . implode('、', $sib) . '」是同一条线索' : '')
        : '（这条你已经查过了。）'];
    $left = [];
    foreach (crrg_seal_paths_full() as $node2 => $p2) {
        if (crrg_seal_node_room($node2) !== $room) continue;
        if (crrg_seal_path_done($s, $node2)) continue;
        if (!$inScope($node2)) continue;
        $left[] = $node2;
    }
    $left = crrg_seal_nodes_dedup($left);
    if ($left) { $out[] = '（这间还能看：' . implode('、', $left) . '——用「调查 <关键词>」或「换法 <节点>」。）'; return $out; }
    $todo = [];
    foreach (crrg_seal_paths_full() as $node3 => $p3) {
        $r3 = crrg_seal_node_room($node3);
        if ($r3 === '' || $r3 === $room) continue;
        if (crrg_seal_path_done($s, $node3)) continue;
        if (!$inScope($node3)) continue;
        $todo[$node3] = $r3;
        if (count($todo) >= 3) break;
    }
    $todo = array_intersect_key($todo, array_flip(crrg_seal_nodes_dedup(array_keys($todo))));
    if ($todo) {
        $out[] = '（这间看完了。还没办的有：' . implode('、', array_keys($todo)) . '。）';
        foreach ($todo as $n4 => $r4) {
            $rn4 = function_exists('crrg_npc_room_name') ? crrg_npc_room_name($r4) : $r4;
            $h4 = function_exists('crrg_drill_route_hint') ? crrg_drill_route_hint($room, $r4) : '';
            $out[] = sprintf('· %s（%s）%s', $n4, $rn4, $h4 !== '' ? '：' . $h4 : '');
            break;
        }
    } else { $out[] = '（该看的都看过了——回去整理结论/交单。）'; }
    return $out;
}

