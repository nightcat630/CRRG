/** 排序：把"不掷骰、不要关系、不要钱"的兜底路排前面（列表与按序号选取必须同一顺序） */
function crrg_seal_paths_sorted($list) {
    usort($list, function ($a, $b) {
        $rank = function ($p) {
            $t = $p['type'] ?? '';
            return $t === 'brute' ? 0 : ($t === 'detour' ? 1 : ($t === 'pay' ? 2 : ($t === 'npc' ? 3 : 4)));
        };
        return $rank($a) <=> $rank($b);
    });
    return $list;
}

