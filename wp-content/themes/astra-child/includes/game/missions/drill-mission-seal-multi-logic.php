            if (!empty($p['hp']))     $cost[] = '生命 −' . (int) $p['hp'];
            if (($p['type'] ?? '') === 'brute') $cost[] = '留下隐患';
            $out[] = sprintf('　%d）%s　——　%s', $i, $p['n'], $cost ? implode(' ｜ ', $cost) : '不需代价');
        }
        $out[] = '（用法：「换法 ' . $node . ' ' . $paths[0]['n'] . '」或输入序号，如「换法 ' . $node . ' 2」。）';
        $out[] = '（没门路、没人肯帮、也不想花钱——**就直接硬来**；代价是留个隐患，后面会被翻出来。）';
        $def = crrg_seal_node_default($node);
        if ($def !== '') $out[] = '（**正办**：直接说「处理 ' . $node . '」——默认走「' . $def . '」；上面是备选。）';
        return $out;
    }
    if ($done = crrg_seal_path_done($s, $node)) return crrg_seal_done_msg($s, $pc, $s['room'] ?? '', $done, $node);
    /* 选路：序号或名字 */
    $pick = null;
    foreach ($paths as $i => $p) if ($which === (string) ($i + 1) || $which === $p['n']) { $pick = $p; break; }
    if ($pick === null) {
        foreach ($paths as $p) if (mb_strpos($p['n'], $which) !== false || mb_strpos($which, $p['n']) !== false) { $pick = $p; break; }
    }
    if ($pick === null) return ['（没有这条法子——先「换法 ' . $node . '」看列表。）'];
    $out = ['〔' . $node . '〕用「' . $pick['n'] . '」。'];
    if (function_exists('crrg_drill_mission_tick')) { /* 任务推进在调用方统一处理 */ }
    /* 门槛 */
    if (!empty($pick['cost'])) {
        if ((int) ($pc['money'] ?? 0) < (int) $pick['cost']) return array_merge($out, [sprintf('（钱不够：要 %d 元，你只有 %d。）', (int) $pick['cost'], (int) ($pc['money'] ?? 0))]);
        $pc['money'] = (int) $pc['money'] - (int) $pick['cost'];
    }
    if (!empty($pick['npc'])) {
        $fav = (int) ($pc['npc_fav'][$pick['npc']] ?? 0);
        if ($fav < (int) ($pick['rep'] ?? 0)) {
            return array_merge($out, [sprintf('（%s 现在不肯帮你——好感 %d，至少要 %d。做他的跑腿委托能涨好感。）',
                $pick['npc'], $fav, (int) $pick['rep'])]);
        }
    }
    if (!empty($pick['skill'])) {
        $val = max(1, function_exists('crrg_coc_skill_val') ? crrg_coc_skill_val($pc, $pick['skill']) : 1);
        $r = crrg_coc_check($pick['skill'], $val);
        $out[] = $pick['skill'] . '：' . $r['text'];
        if (crrg_coc_level_rank($r['level']) < 2) {
            $out[] = '（没成。可以再来，或换一条路。）';
            return $out;
        }
    }
    if (!empty($pick['hp'])) {
        $pc['hp'] = max(1, (int) ($pc['hp'] ?? 1) - (int) $pick['hp']);
        $s['flags'][] = 'pending_' . $node;                  // 硬来留下的隐患
    }
    /* 2026-10-01：**动手（战斗）** 类型 —— 这里只记标记 ✓，真正开打交给调用方（那儿有 $uid ✓） */
    if (($pick['type'] ?? '') === 'fight') $s['seal_fight'] = (string) $node;
    foreach ((array) ($pick['text'] ?? []) as $x) $out[] = $x;
    if (!in_array($pick['flag'], (array) ($s['flags'] ?? []), true)) $s['flags'][] = $pick['flag'];
    $clue = crrg_seal_clue_text($node);
    if ($clue) { $out[] = ''; foreach ($clue as $cx) $out[] = $cx; }
    foreach ((array) crrg_seal_check_dossier($s, $node) as $x) $out[] = $x;
    return $out;
}

