/* ══════════ 隐患兑现（2026-10-14，P0.5：补上那条空头承诺 ✓） ══════════
 * 背景：这条线的"硬来"会给玩家留一个 `pending_<节点>`（台词是"隐患日后会被翻出来"✓），
 *   但负责兑现的 `crrg_seal_pending_check()` **全库没有定义** ✗ —— 调用点被 function_exists 静默跳过 ✓
 *   （2026-10-14 的沙盒化设计文档 14 号文 P0.5 点名要补的就是它。）
 *
 * 规矩：① 只看**自己的产物**（pending_<节点> / pendingpaid_<节点>）✓
 *       ② 幂等：兑现过的打 `pendingpaid_<节点>`（已进存档单调护栏 ✓）→ 永不再来 ✓
 *       ③ 一次动作最多兑现一条（别一口气把五条隐患全砸给玩家 ✗）
 *       ④ 玩家可见文案不带内部键 ✓
 */
function crrg_seal_pending_check(&$s, &$pc, $out) {
    $flags = (array) ($s['flags'] ?? []);
    /* 触发时机：玩家已经走到第四幕及以后（或已定档），旧账才可能被翻出来 ✓ */
    $late = false;
    foreach ($flags as $f) {
        if (strpos((string) $f, 'acc_') === 0 || strpos((string) $f, 's4_') === 0 || strpos((string) $f, 's5_') === 0) { $late = true; break; }
    }
    if (!$late) return $out;

    foreach ($flags as $f) {
        $f = (string) $f;
        if (strpos($f, 'pending_') !== 0) continue;
        $node = substr($f, 8);
        if ($node === '' ) continue;
        if (in_array('pendingpaid_' . $node, $flags, true)) continue;      // 已兑现 ✓ 幂等

        $out[] = '';
        $out[] = '〔隐患〕有人把台账翻出来了：**' . $node . '** 那一步当时是"按旧例直接办"——只填了表，没核。';
        $out[] = '（现在没人受伤，但这一步会被记在案上。）';
        if (function_exists('crrg_rep_add')) {
            $n = crrg_rep_add($pc, 'base', -1, '《封条》隐患兑现：' . $node);
            $out[] = sprintf('（基地声望 −1 → %d。）', (int) $n);
        }
        $s['flags'][] = 'pendingpaid_' . $node;                            // 单调护栏已收纳该前缀 ✓
        if (function_exists('crrg_fact_propose')) {                        // 公共发生的事 → 事实表 ✓（独有型）
            crrg_fact_propose('seal.隐患兑现.' . $node, ['uid' => (int) ($pc['uid'] ?? 0)],
                              ['mode' => 'once', 'scope' => 'base'], (int) ($pc['uid'] ?? 0));
        }
        if (function_exists('crrg_evt_emit')) {
            crrg_evt_emit('mission.beat', ['kind' => 'pending_paid', 'node' => $node, 'uid' => (int) ($pc['uid'] ?? 0)],
                          ['src' => 'seal.pending']);
        }
        break;                                                             // 一次动作只兑现一条 ✓
    }
    return $out;
}


/** 《封条》这条链是否"在手"（2026-10-14 补：这是第二处空头承诺 ✓ 门禁 verify-bus 逮到的 ✓）
 *  调用点：`调查 <关键词>` 的闸（drill-part-exec.php:513）—— 本意是"不在链上的玩家别碰这些调查点"，
 *  但函数一直不存在 ✗ → 调用被 function_exists 挡掉 → **闸等于没装** ✗
 *  口径（保守，防锁人）：只要**正在链上**或**碰过链上任何东西**就放行 ✓
 *  —— 已经玩到一半的人不会被关在门外 ✗；完全无关的人会得到一句明确指引 ✓ */
function crrg_seal_chain_in_hand($pc) {
    $m = (string) ($pc['mission'] ?? '');
    if (strpos($m, 'm_mid_seal') === 0) return true;                  // 正拿着
    foreach ((array) ($pc['mission_done'] ?? []) as $d) {
        if (strpos((string) $d, 'm_mid_seal') === 0) return true;      // 做过链上任一环
    }
    foreach ((array) ($pc['flags'] ?? []) as $f) {                    // 碰过链上的旗标也算
        $f = (string) $f;
        foreach (['seal_', 's3_', 's4_', 's5_', 'craft_', 'acc_', 'route_', 'hook_'] as $p) {
            if (strpos($f, $p) === 0) return true;
        }
    }
    return false;
}
