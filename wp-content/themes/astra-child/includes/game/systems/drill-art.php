/**
 * 对齐修正：汉字是全角（占两列），直接用 strlen 排方框会右边错位。
 * 做法：取所有以 | 结尾的「框线」为目标宽度，逐行按显示宽度补空格，使右边框落在同一列。
 */
function crrg_drill_art_fix($art) {
    $lines = explode("\n", trim((string) $art, "\n"));
    $endsBox = function ($l) { return $l !== '' && in_array(substr($l, -1), ['|', '+'], true); };
    $T = 0;
    foreach ($lines as $l) {                       // 基准宽度＝框线的最大显示宽度
        $l = rtrim($l);
        if ($endsBox($l)) $T = max($T, mb_strwidth($l, 'UTF-8'));
    }
    if ($T <= 0) { $out = []; foreach ($lines as $l) $out[] = rtrim($l); return implode("\n", $out); }
    foreach ($lines as $i => $l) {
        $l = rtrim($l);
        if ($l === '') { $lines[$i] = ''; continue; }
        $w = mb_strwidth($l, 'UTF-8');
        if (preg_match('/^[+\-\s]+$/', $l) && substr($l, -1) === '+' && strpos($l, '-') !== false) {   // 横边框：补横线
            $lines[$i] = substr($l, 0, -1) . str_repeat('-', max(0, $T - $w)) . '+';
            continue;
        }
        if (in_array(substr($l, -1), ['|', '+'], true)) {                       // 其它框线：行尾字符前补空格
            $end  = substr($l, -1);
            $body = rtrim(substr($l, 0, -1));
            $pad  = $T - mb_strwidth($body, 'UTF-8') - 1;
            $lines[$i] = $body . ($pad > 0 ? str_repeat(' ', $pad) : '') . $end;
            continue;
        }
        $lines[$i] = $l . ($w < $T ? str_repeat(' ', $T - $w) : '');             // 说明行也补齐（右侧不留毛边）
    }
    return implode("\n", $lines);
}
