<?php
/**
 * 镇上两个 NPC 的话题（2026-10-29 重写）
 * ------------------------------------------------------------
 * 问题所在：这两个 NPC 由 `drill-mission-seal2.php` 用 `crrg_dlg_register` 定义，
 * 里面 `'topics' => []`（空）。我在 town-fixers.php 里用 `crrg_dlg_define` 想覆盖，
 * 但 `crrg_dlg_register` 走的是**另一个注册表**，覆盖不到 → 话题一直是 0。
 *
 * 现在的做法：**直接用 crrg_dlg_register 再注册一次**（同 id 覆盖），把话题写进去。
 * 优先级 99，跑在所有 seal 文件之后。
 */
if (!defined('ABSPATH')) exit;

add_action('init', function () {
    if (!function_exists('crrg_dlg_register')) return;

    crrg_dlg_register('tw_junk_man', [
        'name' => '孙德发',
        'room' => 'tw_junk',
        'look' => '废品站老板，围着围裙，一边拨算盘一边跟你说话。',
        'topics' => [
            '收什么' => [
                'label' => '收废品都收什么',
                'text' => [
                    '「铁、铜、纸壳、旧家电。」他拿脚踢了踢脚边一摞铁皮。',
                    '「最近收着不少好东西——卫生院扔出来的药瓶子，整箱整箱的。」',
                ],
            ],
            '夜里' => [
                'label' => '夜里出不出车',
                'text' => [
                    '「出。夜里价高。」他把烟按在秤砣上。',
                    '「前两天夜里路过东街，看见有人往老校舍那边搬东西，用板车，盖着布。」',
                ],
            ],
            '镇上' => [
                'label' => '镇上近来怎么样',
                'text' => ['「不怎么。」他想了想，「就是死人多。」'],
            ],
        ],
    ]);

    crrg_dlg_register('tw_farm_man', [
        'name' => '赵铁',
        'room' => 'tw_farm',
        'look' => '农机站的老师傅，手上抹着机油，正拆一只旧电瓶。',
        'topics' => [
            '拖拉机' => [
                'label' => '拖拉机修好了没',
                'text' => [
                    '「修是修好了。」他手上还沾着机油，「就是最近老有人半夜来借。」',
                    '「借了不还，也不说去哪儿。」',
                ],
            ],
            '后山' => [
                'label' => '后山那条路通哪儿',
                'text' => [
                    '「通营地。以前是矿上开的道。」',
                    '「现在有人把路口的封土又填回去了——填得潦草，一看就不是干这行的。」',
                ],
            ],
            '东街' => [
                'label' => '东街那边呢',
                'text' => ['「东街？」他把扳手放下，「东街晚上别去。灯亮着也别去。」'],
            ],
        ],
    ]);
}, 99);
